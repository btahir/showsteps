// Regenerates brand-fonts.ts (base64 of the .woff2 files next to this script) so the exported HTML
// guide can embed Rethink Sans and Fragment Mono without any fetch. Sources: packages/brand/fonts
// (SIL OFL 1.1, see OFL-RethinkSans.txt and OFL-FragmentMono.txt).
// Run: node packages/core/assets/fonts/build-brand-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const b64 = (f) => readFileSync(join(dir, f)).toString("base64");
const out = `// GENERATED by build-brand-fonts.mjs. Do not edit.
// Rethink Sans (variable, weights 400-800) and Fragment Mono, SIL OFL 1.1.
export const RETHINK_SANS_LATIN_B64 = "${b64("RethinkSans-Variable-latin.woff2")}";
export const RETHINK_SANS_LATIN_EXT_B64 = "${b64("RethinkSans-Variable-latin-ext.woff2")}";
export const FRAGMENT_MONO_LATIN_B64 = "${b64("FragmentMono-Regular-latin.woff2")}";
`;
writeFileSync(join(dir, "brand-fonts.ts"), out);
console.log("wrote brand-fonts.ts", out.length, "bytes");

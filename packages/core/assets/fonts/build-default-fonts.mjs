// Regenerates default-fonts.ts (base64 of the .woff files next to this script) so the
// default PDF fonts ship inside the JS bundle: no fetch, no fs, works in an extension worker.
// Source Sans 3 comes as one file per script (unicode-range subsets from @fontsource/source-sans-3 5.3.0);
// the PDF exporter picks the face that has each character.
// Run: node packages/core/assets/fonts/build-default-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const b64 = (f) => readFileSync(join(dir, f)).toString("base64");
const scripts = ["latin", "latin-ext", "cyrillic", "cyrillic-ext", "greek"];
const faces = scripts
  .map((s) => `  { script: "${s}", regular: "${b64(`SourceSans3-Regular-${s}.woff`)}", bold: "${b64(`SourceSans3-Bold-${s}.woff`)}" },`)
  .join("\n");
const out = `// GENERATED by build-default-fonts.mjs. Do not edit.
// Source Sans 3 (SIL OFL 1.1, see OFL.txt) from @fontsource/source-sans-3 5.3.0, base64 WOFF per script.
export const SOURCE_SANS_3_REGULAR_B64 = "${b64("SourceSans3-Regular-latin.woff")}";
export const SOURCE_SANS_3_BOLD_B64 = "${b64("SourceSans3-Bold-latin.woff")}";
/** All faces in lookup order (latin first). */
export const SOURCE_SANS_3_FACES: { script: string; regular: string; bold: string }[] = [
${faces}
];
`;
writeFileSync(join(dir, "default-fonts.ts"), out);
console.log("wrote default-fonts.ts", out.length, "bytes");
